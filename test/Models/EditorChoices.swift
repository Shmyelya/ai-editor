enum ParaphraseTone: String, CaseIterable, Identifiable {
    case neutral
    case business
    case friendly
    case simple

    var id: String { rawValue }

    var title: String {
        switch self {
        case .neutral:
            "нейтральный"
        case .business:
            "деловой"
        case .friendly:
            "дружелюбный"
        case .simple:
            "простой"
        }
    }

    func appendingInstruction(to prompt: String) -> String {
        guard self != .neutral else { return prompt }
        return "\(prompt) Тон текста — \(title)."
    }
}
